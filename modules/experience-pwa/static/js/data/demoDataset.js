const DAY = 86400000;
const iso = (now, days) => new Date(now - days * DAY).toISOString();
function ageLabel(days) {
  if (days <= 0) return 'Just now';
  if (days === 1) return 'Yesterday';
  return days + ' days ago';
}
function projectFields(ref) {
  const p = DEMO_PROJECTS.find((x) => x.Project_ReferenceID === ref) || {};
  return { client_name: p.client_name, project_name: p.project_name, projectId: String(p.project_name || '').toLowerCase(), Project_ReferenceID: ref, opportunity_id: (p.opportunity_numbers || [])[0] || '' };
}

// Pure: returns a complete FailoverDB state (all five collections, so
// readLocal never fills a gap from mockSeed). No storage access here.
export function buildDemoState(now = Date.now()) {
  const projects = DEMO_PROJECTS.map(({ ageDays, ...p }) => ({ ...p, anchor_id: p.Project_ReferenceID, syncStatus: 'synced', created_at: iso(now, ageDays) }));
  const timeline = DEMO_CARDS.map(({ ageDays, project, nodes, ...c }) => {
    const card = {
      ...projectFields(project), ...c,
      contributor: c.author, detail: c.content,
      timestamp: ageLabel(ageDays), piiStatus: 'Clean', syncStatus: 'synced', vectorSyncStatus: 'synced',
      created_at: iso(now, ageDays), processed_at: iso(now, ageDays),
    };
    if (Array.isArray(nodes)) card.nodes = nodes.map(({ ageDays: a, ...n }) => ({ ...n, at: iso(now, a) }));
    return card;
  });
  const notes = DEMO_NOTES.map(({ ageDays, project, ...n }) => ({
    ...projectFields(project), ...n,
    projectId: projectFields(project).project_name, contributor: n.author,
    original: n.content, rephrased: n.content, detail: n.content, tags: [],
    piiStatus: 'Clean', syncStatus: 'synced', timestamp: ageLabel(ageDays), created_at: iso(now, ageDays),
  }));
  return {
    version: DEMO_DATASET_VERSION, dataset: DEMO_DATASET_VERSION, seeded_at: new Date(now).toISOString(),
    clients: JSON.parse(JSON.stringify(DEMO_CLIENTS)), projects, timeline, notes, archived: [],
  };
}

export default buildDemoState;
